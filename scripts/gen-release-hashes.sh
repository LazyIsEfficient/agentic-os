#!/usr/bin/env bash
# gen-release-hashes.sh — regenerate assets/release-hashes.txt.
#
# The file lists "<sha256>  <path>" for every file under .claude/{skills,
# agents,commands,hooks} in every vX.Y.Z release tag (path relative to
# .claude/, deduplicated, byte-sorted). install.sh / install.ps1 use it when
# adopting an install that predates the manifest: a file whose content matches
# ANY earlier release's copy of that path is an unmodified AgenticOS file and
# is updated, instead of being kept forever as "modified locally".
#
# Deterministic: same tags in, same bytes out. Run at every release, before
# tagging (RELEASING.md step 0); scripts/release.sh refuses to build while the
# committed file is stale.
#
# Usage:
#   bash scripts/gen-release-hashes.sh           # rewrite the file
#   bash scripts/gen-release-hashes.sh --check   # exit 1 if it is stale
#   --exclude vX.Y.Z   ignore one tag (release.sh: the version being built,
#                      which may already be tagged when rebuilt from the tag)
# Needs the release tags locally (`git fetch --tags`); exits 2 without them.
set -euo pipefail
export LC_ALL=C

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
OUT="$ROOT/assets/release-hashes.txt"
CHECK=false
EXCLUDE=""
while [[ $# -gt 0 ]]; do
  case "$1" in
    --check) CHECK=true ;;
    --exclude) EXCLUDE="${2:?--exclude needs a tag}"; shift ;;
    *) echo "usage: gen-release-hashes.sh [--check] [--exclude vX.Y.Z]" >&2; exit 2 ;;
  esac
  shift
done

if command -v shasum &>/dev/null; then SHA=(shasum -a 256); else SHA=(sha256sum); fi

tags="$(git -C "$ROOT" tag -l 'v[0-9]*.[0-9]*.[0-9]*' | grep -E '^v[0-9]+\.[0-9]+\.[0-9]+$' | grep -vxF -- "${EXCLUDE:-}" | sort -t. -k1.2,1n -k2,2n -k3,3n || true)"
if [[ -z "$tags" ]]; then
  echo "gen-release-hashes: no vX.Y.Z tags found (shallow clone? run: git fetch --tags)" >&2
  exit 2
fi

tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT

for t in $tags; do
  mkdir -p "$tmp/$t"
  for d in skills agents commands hooks; do
    git -C "$ROOT" cat-file -e "$t:.claude/$d" 2>/dev/null || continue
    git -C "$ROOT" archive "$t" ".claude/$d" | tar -x -C "$tmp/$t"
  done
  [[ -d "$tmp/$t/.claude" ]] || continue
  echo "$t" >> "$tmp/hashed"
  (cd "$tmp/$t/.claude" && find . -type f -print0 | xargs -0 "${SHA[@]}") \
    | awk '{ p = substr($0, 67); sub(/^\.\//, "", p); if (p ~ /^[A-Za-z0-9._@+\/-]+$/) print substr($0, 1, 64) "  " p }'
done | sort -u > "$tmp/body"

{
  echo "# Generated by scripts/gen-release-hashes.sh — do not edit by hand."
  echo "# Tags: $( (cat "$tmp/hashed" 2>/dev/null || true) | tr '\n' ' ' | sed 's/ $//')"
  cat "$tmp/body"
} > "$tmp/out"

if [[ "$CHECK" == "true" ]]; then
  if ! cmp -s "$tmp/out" "$OUT"; then
    echo "gen-release-hashes: $OUT is stale — run: bash scripts/gen-release-hashes.sh" >&2
    exit 1
  fi
  echo "gen-release-hashes: up to date ($(wc -l < "$tmp/body" | tr -d ' ') entries)"
  exit 0
fi
mv "$tmp/out" "$OUT"
echo "gen-release-hashes: wrote $OUT ($(wc -l < "$tmp/body" | tr -d ' ') entries)"
