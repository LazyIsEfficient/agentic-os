#!/usr/bin/env bash
#
# build-consumer-doctrine.sh — regenerate assets/consumer/doctrine.md from
# .claude/rules/*.md.
#
# The consumer doctrine is what `install.sh --with-doctrine` installs: the
# grounding / verification / review-tier rules, minus this repo's own material
# (memory paths, dispatch rules naming this repo's agents, maintainer scripts).
# Each source rule is copied verbatim except for the lines in REWRITES below.
# A rewrite must match exactly one line of its source, so when a rule changes
# under a rewrite the build fails instead of silently shipping stale text.
#
# validate.sh invariant `consumer-doctrine` runs `--check` (whole-file diff)
# when this script is present, and checks that every source marker in the
# doctrine names a rule file on disk.
#
# Usage:
#   bash scripts/build-consumer-doctrine.sh           # rewrite the doctrine
#   bash scripts/build-consumer-doctrine.sh --check   # exit 1 + diff if stale

set -euo pipefail
export LC_ALL=C

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
RULES_DIR="$ROOT/.claude/rules"
TARGET="$ROOT/assets/consumer/doctrine.md"

# Shipped rules, in order. memory-discipline, subagent-dispatch, briefing,
# anti-patterns and communication are repo-only and deliberately left out.
RULES=(factual-correctness grounding review-tiers verification)

# rule <TAB> exact source line <TAB> replacement line ("@DELETE" drops the line).
# Read with `read -d ''`, not a command substitution around a heredoc: macOS
# /bin/bash 3.2 mis-parses the apostrophes of a quoted heredoc inside $(...).
IFS= read -r -d '' REWRITES <<'EOF' || true
grounding	The most common failure mode in agentic work is **generate-without-reading**: an agent states facts about files, functions, or state it never actually read. These rules apply to every agent this repo dispatches — no exceptions.	The most common failure mode in agentic work is **generate-without-reading**: an agent states facts about files, functions, or state it never actually read. These rules apply to you and to every agent you dispatch — no exceptions.
review-tiers	Every check in this repo's review machinery belongs to exactly one tier, sorted	Every check in your review machinery belongs to exactly one tier, sorted
review-tiers	- **TIER 0 — deterministic.** `scripts/validate.sh`, linters, any script that	- **TIER 0 — deterministic.** Your project's validators, linters, any script that
review-tiers	   `scripts/validate.sh`.	   your project's validator script.
review-tiers	  End with the machine verdict block — `pass | fix-before-merge | hold`, where	  Only Tier 0/1 findings may justify a `hold` verdict.
review-tiers	  only Tier 0/1 findings may justify `hold`	@DELETE
review-tiers	  ([review-verdict.md](../references/review-verdict.md), parsed by	@DELETE
review-tiers	  `scripts/parse-verdict.sh`).	@DELETE
review-tiers	- Triaging? Run `/triage-findings` — it proposes promotions and retirements;	- Triaging? Use the `findings-ledger` skill — it proposes promotions and retirements;
EOF

err() { printf 'build-consumer-doctrine: %s\n' "$*" >&2; exit 1; }

[[ -d "$RULES_DIR" ]] || err "missing $RULES_DIR"

# Rewrites for rule $1 are applied by awk; each must hit exactly one line.
curate() {
  local name="$1" src="$RULES_DIR/$1.md"
  [[ -f "$src" ]] || err "RULES names '$name' but $src does not exist"
  [[ -z "$(tail -c1 "$src")" ]] || err "$src lacks a trailing newline — add one"
  printf '%s\n' "$REWRITES" | awk -F'\t' -v r="$name" '$1 == r' > "$WORK/rw"
  REWRITES_FILE="$WORK/rw" awk -v src="$src" '
    BEGIN {
      FS = "\t"
      while ((getline line < ENVIRON["REWRITES_FILE"]) > 0) {
        split(line, f, "\t"); n++; from[n] = f[2]; to[n] = f[3]; hit[n] = 0
      }
      FS = "\n"
    }
    {
      for (i = 1; i <= n; i++) if ($0 == from[i]) {
        hit[i]++
        if (to[i] != "@DELETE") print to[i]
        next
      }
      print
    }
    END {
      for (i = 1; i <= n; i++) if (hit[i] != 1) {
        printf "build-consumer-doctrine: rewrite for %s matched %d lines (want 1): %s\n", src, hit[i], from[i] > "/dev/stderr"
        bad = 1
      }
      exit bad
    }' "$src" || err "the rules changed under a rewrite — update REWRITES in $0"
}

generate() {
  cat <<'EOF'
<!-- GENERATED by scripts/build-consumer-doctrine.sh from .claude/rules/ in
     the AgenticOS repo — do not edit. Installed by `install.sh --with-doctrine`
     and removed by `install.sh --uninstall`. -->
# AgenticOS doctrine — grounding, verification, review tiers

These rules apply to every session and every agent you dispatch. They exist to
cut two failure modes: claims nobody checked, and gates that block on opinion.
EOF
  local name
  for name in "${RULES[@]}"; do
    printf '\n<!-- source: .claude/rules/%s.md -->\n' "$name"
    curate "$name"
  done
}

WORK="$(mktemp -d)"
trap 'rm -rf "$WORK"' EXIT
generate > "$WORK/out"

if grep -q 'agentic-os:doctrine:' "$WORK/out"; then
  err "the doctrine must not contain the installer's block markers (agentic-os:doctrine:*)"
fi

if [[ "${1:-}" == "--check" ]]; then
  if ! diff -u "$TARGET" "$WORK/out"; then
    err "$TARGET is out of sync with .claude/rules/ — run: bash scripts/build-consumer-doctrine.sh"
  fi
  echo "build-consumer-doctrine: doctrine is in sync"
else
  [[ -L "$TARGET" ]] && err "$TARGET is a symlink — refusing to overwrite"
  cp "$WORK/out" "$TARGET"
  echo "build-consumer-doctrine: wrote $TARGET"
fi
